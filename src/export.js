function exportHTML() {
  const stats = loadJSON(GLOBAL_STATS_FILE);
  if (!stats || stats.totalSessions === 0) {
    console.log('No data to export.');
    return;
  }
  const date = new Date().toISOString().split('T')[0];
  const outFile = `${EXPORTS_DIR}/report-${date}.html`;
  writeFileSync(outFile, buildHtml(stats, date));
  console.log(`Exported to: ${outFile}`);
  return outFile;
}

// Guarded: importing this module for tests must not write a report into the
// user's exports directory.
if (isMainModule(import.meta.url)) {
  const format = process.argv[2] || 'md';
  switch (format) {
    case 'md':
    case 'markdown':
      exportMarkdown();
      break;
    case 'html':
      exportHTML();
      break;
    default:
      console.log('Usage: cco-export [md|html]');
  }
}
